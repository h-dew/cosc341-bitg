package com.example.cosc341_bitg;

public class Match {
    public String name;
    public int age;
    public String location;
    public String interests;
    public String bio;

    public Match(String name, int age, String location, String interests, String bio) {
        this.name = name;
        this.age = age;
        this.location = location;
        this.interests = interests;
        this.bio = bio;
    }
}